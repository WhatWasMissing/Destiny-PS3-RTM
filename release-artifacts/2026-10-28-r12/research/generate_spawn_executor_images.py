from __future__ import annotations

import hashlib
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
SPECS = (
    (
        "SPAWN_PROGRAM",
        ROOT / "research" / "spawn-program-first-slot.bin",
        0x0183E400,
        2908,
        "3b4a46a3aa4246709d99c8e71a643dabdea134f5f387498d1cd375da0885fb76",
    ),
    (
        "BOOTSTRAP_EXECUTOR",
        ROOT / "research" / "bootstrap-executor.bin",
        0x0183E000,
        292,
        "616e8294b969ad36fdb78844a0bafb7dcc9b11a25384c7288201c6aed6d24d1f",
    ),
)


def js_array(name: str, value: bytes) -> str:
    encoded = value.hex().upper()
    lines = [f"    '{encoded[index:index + 96]}'" for index in range(0, len(encoded), 96)]
    return f"  const {name}_HEX = [\n" + ",\n".join(lines) + "\n  ].join('');"


def build() -> str:
    values = []
    for name, path, address, expected_length, expected_hash in SPECS:
        raw = path.read_bytes()
        digest = hashlib.sha256(raw).hexdigest()
        if len(raw) != expected_length or digest != expected_hash:
            raise ValueError(
                f"{path.name} changed: length={len(raw)}, sha256={digest}; "
                f"expected length={expected_length}, sha256={expected_hash}"
            )
        values.append((name, raw, address, digest))

    constants = "\n\n".join(js_array(name, raw) for name, raw, _, _ in values)
    metadata = ",\n".join(
        f"    {name.lower()}: Object.freeze({{ base: 0x{address:08x}, length: {len(raw)}, sha256: '{digest}' }})"
        for name, raw, address, digest in values
    )
    return f"""// Generated by research/generate_spawn_executor_images.py from the audited PPC binaries.
(function (root, factory) {{
  'use strict';
  const api = factory();
  if (typeof module === 'object' && module && module.exports) module.exports = api;
  if (root) root.DESTINY_RTM_SPAWN_EXECUTOR_IMAGES = api;
}})(typeof globalThis !== 'undefined' ? globalThis : this, function () {{
  'use strict';

{constants}

  function decodeHex(hex) {{
    if (hex.length % 2 || !/^(?:[0-9A-F]{{2}})*$/.test(hex)) throw new Error('Embedded executor image is invalid');
    const bytes = new Uint8Array(hex.length / 2);
    for (let i = 0; i < bytes.length; i++) bytes[i] = Number.parseInt(hex.slice(i * 2, i * 2 + 2), 16);
    return bytes;
  }}

  const metadata = Object.freeze({{
{metadata}
  }});
  return Object.freeze({{
    metadata,
    createSpawnProgram: () => decodeHex(SPAWN_PROGRAM_HEX),
    createBootstrapExecutor: () => decodeHex(BOOTSTRAP_EXECUTOR_HEX)
  }});
}});
"""


if __name__ == "__main__":
    output = ROOT / "source" / "js" / "spawn-executor-images.js"
    output.write_text(build(), encoding="utf-8", newline="\n")
    print(f"wrote {output.relative_to(ROOT)}")
